// 深检站.js —— 闸序列第二道：模型判质量。初检判形状（领域/校验），深检判「做的对不对、够不够」。
//
// 判官是一个只读会话（编排/会话，用途 审），看的是证据包（改动清单、diff、回执、日志尾）加工单正文。
// 它只出结论与理由，**不改文件、不改状态**：结论由这里解读成 通过|打回，记闸与迁移是调用方（取单器/一个专项）的事。
// 解读**失效方向是拦**：回复里没有「结论：通过」这一行，一律当打回——判官含糊，不许算过。
//
// 异厂评审台（各厂互不可见独立出意见）是加强项，另建 编排/评审台；这里是单判官。
'use strict';

const diff上限 = 12000;   // 字；超了截断并注明，别把 token 烧在 diff 上

/** 深检的提示词：单 + 证据包，末尾写死结论格式。 */
function 深检提示词(单, 包, 选项) {
  const o = 选项 || {};
  const 上限 = o.diff上限 || diff上限;
  const 改 = (包.改动 && 包.改动.文件) || [];
  let diff = String((包.改动 && 包.改动.diff) || '');
  if (diff.length > 上限) diff = diff.slice(0, 上限) + `\n…（diff 共 ${(包.改动.diff || '').length} 字，截到 ${上限}）`;
  const 段 = [];
  段.push(`# 深检 · 工单 ${单.id}${单.title ? '：' + 单.title : ''}`);
  段.push(`性质：${单.性质 || '?'}　职能：${单.职能 || '?'}`);
  if (单.正文) { 段.push(''); 段.push('## 工单要求'); 段.push(String(单.正文).trim()); }
  if (单.进项 && Object.keys(单.进项).length) { 段.push(''); 段.push('## 进项'); for (const [k, v] of Object.entries(单.进项)) 段.push(`- ${k}：${Array.isArray(v) ? v.join('、') : v}`); }
  段.push(''); 段.push('## 执行者交回的证据包');
  段.push(`- 改动文件（${改.length}）：${改.join('、') || '（无）'}`);
  段.push(`- 执行：${包.结果 ? `${包.结果.退出} · ${包.结果.耗时ms}ms` : '?'} · harness ${包.harness ? 包.harness.名 : '?'}`);
  段.push(''); 段.push('### 回执'); 段.push(String(包.回执 || '').trim() || '（空）');
  段.push(''); 段.push('### diff'); 段.push('```diff'); 段.push(diff || '（无）'); 段.push('```');
  if (包.日志尾) { 段.push(''); 段.push('### 日志尾'); 段.push('```'); 段.push(String(包.日志尾).slice(-2000)); 段.push('```'); }
  段.push('');
  段.push('## 你要判的');
  段.push('1. 改动是不是工单要求的那件事，没多做没少做；');
  段.push('2. 改动本身对不对（逻辑、边界、命名与工程约定）；');
  段.push('3. 回执说的和 diff 做的是不是一回事。');
  段.push('你可以用 Read/Grep/Glob 看工作目录里的文件核对，**不许改任何文件，不许判定流程下一步**。');
  段.push('');
  段.push('## 回复格式（最后两行必须是）');
  段.push('结论：通过　或　结论：打回');
  段.push('理由：一句话；打回时逐条列要补什么');
  return 段.join('\n') + '\n';
}

/** 解读判官回复。没有「结论：通过」这一行一律打回。 */
function 解读结论(文本) {
  const s = String(文本 || '');
  const m = /结论\s*[:：]\s*(通过|打回|上呈)/g;
  let 末 = null, x;
  while ((x = m.exec(s))) 末 = x[1];
  const 理 = /理由\s*[:：]\s*([\s\S]+?)$/m.exec(s);
  const 因 = 理 ? 理[1].trim() : '';
  if (!末) return { 结果: '打回', 因: '判官没按格式给结论（缺「结论：通过/打回」行）——含糊不算过', 含糊: true };
  return { 结果: 末, 因: 因 || (末 === '通过' ? '判官通过' : '判官没写理由'), 含糊: false };
}

/**
 * 深检一张单。
 * @param 依赖 { 问(提示词) → { 文本, 会话id?, 用量? } }   通常来自 编排/会话.开会话(协议, {用途:'审'}).问
 */
async function 深检(单, 包, 依赖) {
  if (!依赖 || typeof 依赖.问 !== 'function') throw new Error('深检站：没注入 问——判官会话是必需的');
  const 提示词 = 深检提示词(单, 包, 依赖);
  const 回 = await 依赖.问(提示词);
  const 读 = 解读结论(回 && 回.文本);
  return { 结果: 读.结果, 因: 读.因, 含糊: 读.含糊, 原文: (回 && 回.文本) || '', 会话id: 回 && 回.会话id, 用量: 回 && 回.用量 };
}

module.exports = { 深检提示词, 解读结论, 深检, diff上限 };
