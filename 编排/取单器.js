// 取单器.js —— 研发环的常驻那一段：收草稿 → 成单 → 审批 → 按拍取单 → 派 → 跑 → 证据包 → 初检 → 深检。
//
// 它把 tools/一张单.js 那条手工链变成能反复拍的东西。规矩全在领域层，这里只是把它们按顺序串起来：
//   · 入口必经 单型.剥(草稿,「项管」)：项管只能写项管该写的字段，代码写的（id/状态/时间/闸序列/履历）由入口剥掉
//   · 成单时 状态机.编闸序列 编上闸序列（制作人 09-04 23:51 定）
//   · 拆单判据③ 在这儿判：进项未过闸不派——上游单没到 完成/归档，下游不派
//   · 规模=战役 的单本身不派
//   · 初检打回 → 自修（把打回理由追加进提示词再跑）；自修到上限 → 三振进 待处理
//   · 初检过后由代码从证据包的改动清单写 单.产出（修复单还写 防复发判据）
//   · 路由上呈 / 适配器炸 → 待处理，交人分诊，不静默重试
//
// **依赖全注入，缺了就炸**：存单 / 存包 / 记事 / 读文件 / 存在 缺一不可——不注入就静默不落盘、不留痕，不许。
// 钟 与 适配器们 有真的默认值。判据喂假的就能跑整链，不碰网。
'use strict';
const 单型 = require('../领域/单型.js');
const 状态机 = require('../领域/状态机.js');
const 协议 = require('../领域/协议.js');
const 权限 = require('../领域/权限.js');
const 校验 = require('../领域/校验.js');
const 架构树 = require('../领域/架构树.js');
const 证据 = require('../内核/证据.js');
const 时钟 = require('../内核/时钟.js');
const 适配器 = require('./适配器.js');
const 装配器 = require('./装配器.js');

const 可派的态 = Object.freeze(['待派', '已排期']);
const 优先序 = { P0: 0, P1: 1, P2: 2, P3: 3 };
const 数组 = (x) => (Array.isArray(x) ? x : x === undefined || x === null ? [] : [x]);

function 要(依赖, 名) {
  if (!依赖 || typeof 依赖[名] !== 'function') throw new Error(`取单器：没注入 ${名}——不注入就静默不落盘/不留痕，不许`);
  return 依赖[名];
}
const 钟of = (依赖) => (依赖 && 依赖.钟) || 时钟.真钟();

let 真适配器们 = null;
function 默认适配器们() {
  if (!真适配器们) 真适配器们 = { claude: require('./适配器-claude.js') };
  return 真适配器们;
}

/** 缺省发号：同前缀最大号 +1。 */
function 默认发号(池, 前缀) {
  const p = 前缀 || 'TK';
  let 最大 = 0;
  for (const t of (池.工单们 || [])) { const m = new RegExp(`^${p}-(\\d+)$`).exec(t.id || ''); if (m) 最大 = Math.max(最大, Number(m[1])); }
  return `${p}-${最大 + 1}`;
}

/** 校验单要的上下文，从池里推。 */
function 上下文从池(池, 草稿, 存在) {
  const 专项们 = 池.专项们 || [], 特性们 = 池.特性们 || [], 工单们 = 池.工单们 || [];
  const 归 = (草稿 && 草稿.归属) || {};
  return {
    存在: 存在 || (() => false),
    专项: (id) => 专项们.find((s) => s.id === id) || null,
    特性: (id) => 特性们.find((f) => f.id === id) || null,
    同专项单们: 归.专项 ? 工单们.filter((t) => t.归属 && t.归属.专项 === 归.专项) : [],
  };
}

/**
 * 收草稿 → 成单。草稿只带项管该写的字段；成单由代码发号、置 待审、盖时间、编闸序列。
 * @returns { 行, 违? , 单? }
 */
function 收草稿(草稿, 池, 依赖) {
  const 钟 = 钟of(依赖);
  const 存在 = 要(依赖, '存在');
  const 净 = 单型.剥(草稿, '项管');
  const 上 = 上下文从池(池, 净, 存在);
  const 校 = 单型.校验单(净, 上);
  if (!校.行) return { 行: false, 违: 校.违 };
  const 现在 = 钟.现在();
  const id = (依赖 && typeof 依赖.发号 === 'function') ? 依赖.发号(净, 池) : 默认发号(池, 依赖 && 依赖.前缀);
  let 单 = { ...净, id, 状态: '待审', 创建时间: 现在, 更新时间: 现在, 履历: [] };
  单 = 状态机.编闸序列(单);
  const 再 = 单型.校验单(单, 上);
  if (!再.行) return { 行: false, 违: 再.违 };
  要(依赖, '存单')(单);
  要(依赖, '记事')({ 类: '成单', 单: 单.id, 职能: 单.职能, 性质: 单.性质, 闸: [...单.闸序列.闸] });
  return { 行: true, 单 };
}

/** 审批：人的动作。通过 → 待派；不通过 → 废弃。 */
function 审批(单, 凭, 依赖) {
  const p = 凭 || {};
  const 到 = p.结果 === '拒' ? '废弃' : '待派';
  const 新 = 状态机.迁(单, 到, { 操作者: p.操作者, 因: p.因 || (到 === '待派' ? '审批通过' : '审批不通过'), 时刻: p.时刻 || 钟of(依赖).现在() });
  要(依赖, '存单')(新);
  要(依赖, '记事')({ 类: '审批', 单: 新.id, 到, 操作者: p.操作者 });
  return 新;
}

/**
 * 取单：下一张能派的。按优先级、再按创建时间。
 * 拆单判据③：进项未过闸不派——每一项进项要么盘上已有，要么由 完成/归档 的上游单产出。
 * 规模=战役 不派。跳过的都写因，不静默。
 */
function 取单(池, 依赖) {
  const 存在 = 要(依赖, '存在');
  const 工单们 = 池.工单们 || [];
  const 按id = new Map(工单们.map((t) => [t.id, t]));
  const 图 = 架构树.数据流(工单们);
  const 因们 = [];
  const 候 = 工单们.filter((t) => 可派的态.includes(t.状态))
    .sort((a, b) => ((优先序[a.优先级] ?? 9) - (优先序[b.优先级] ?? 9)) || String(a.创建时间 || '').localeCompare(String(b.创建时间 || '')));
  for (const t of 候) {
    if (t.规模 === '战役') { 因们.push({ 单: t.id, 因: '规模=战役，本身不派，要先拆' }); continue; }
    const 卡 = [];
    for (const [k, v] of Object.entries(t.进项 || {})) for (const 路 of 数组(v)) {
      if (存在(路)) continue;
      const 上 = (图.get(t.id) || []).map((u) => 按id.get(u)).find((s) => s && [...Object.values(s.产出 || {}), ...Object.values(s.预计产出 || {})].some((x) => 数组(x).includes(路)));
      if (上 && (上.状态 === '完成' || 上.状态 === '归档')) continue;
      卡.push(`${k}=${路}${上 ? `（上游 ${上.id} 在 ${上.状态}，没过闸）` : '（不在盘上，也没人产出）'}`);
    }
    if (卡.length) { 因们.push({ 单: t.id, 因: '进项未过闸不派：' + 卡.join('；') }); continue; }
    return { 单: t, 因们 };
  }
  return { 单: null, 因们 };
}

/** 初检过后，产出由代码从证据包的改动清单写——执行者不填。 */
function 算产出(单, 包) {
  const 改 = (包 && 包.改动 && 包.改动.文件) || [];
  const 测 = 改.filter((f) => /(^|\/)tests?\//i.test(f));
  const 非测 = 改.filter((f) => !/(^|\/)tests?\//i.test(f));
  const 一或多 = (a) => (a.length === 1 ? a[0] : a);
  switch (单.性质) {
    case '调研': { const md = 改.find((f) => /\.md$/i.test(f)); return md ? { 产出: { 方案: md } } : { 产出: {} }; }
    case '新建': return { 产出: 非测.length ? { 资产: 一或多(非测) } : {} };
    case '修复': return { 产出: 非测.length ? { 资产: 一或多(非测) } : {}, ...(测.length ? { 防复发判据: 测[0] } : {}) };
    case '装配': return { 产出: 改.length ? { 成果: 一或多(改) } : {} };
    default: return { 产出: {} };
  }
}

/**
 * 派：路由 → 执行卷 → 在途 → 装配 → 跑 → 证据包 → 初检 → 深检 / 自修 / 三振。
 * @param 依赖 { 存单, 存包, 记事, 读文件, 取协议(单)→{执行,上级}, 工作目录, 钟?, 适配器们?, 跑依赖?, 自修上限?, 超时ms? }
 * @returns { 单, 结果: '进深检'|'自修'|'三振'|'上呈'|'炸', 检? }
 */
async function 派(单0, 依赖) {
  const 存单 = 要(依赖, '存单'), 存包 = 要(依赖, '存包'), 记事 = 要(依赖, '记事'), 读文件 = 要(依赖, '读文件'), 取协议 = 要(依赖, '取协议');
  if (!依赖.工作目录) throw new Error('取单器：没给 工作目录');
  const 钟 = 钟of(依赖);
  const 时 = () => 钟.现在();
  const 上限 = Number.isInteger(依赖.自修上限) ? 依赖.自修上限 : 2;
  let 单 = 单0;
  const 协议们 = 取协议(单);
  if (!协议们 || !协议们.执行) throw new Error(`取单器：取协议 没给「${单.职能}」的执行协议`);

  let 路;
  try { 路 = 适配器.路由(单, 协议们.上级); } catch (e) {
    if (e.code !== '路由上呈') throw e;
    单 = 状态机.迁(单, '待处理', { 操作者: '取单器', 因: `路由上呈：${e.message}`, 时刻: 时() });
    存单(单); 记事({ 类: '上呈', 单: 单.id, 因: e.message });
    return { 单, 结果: '上呈' };
  }
  const 声 = 协议.权限声明(协议们.执行);
  const 卷 = 权限.编译执行卷(单, 声, 单.收紧);
  单 = 状态机.迁(单, '在途', { 操作者: '取单器', 因: `派给 ${路.harness}（${路.因}）`, 时刻: 时() });
  存单(单); 记事({ 类: '派', 单: 单.id, harness: 路.harness, 执行卷: 卷.哈希 });

  const 进项内容 = {};
  for (const [k, v] of Object.entries(单.进项 || {})) 进项内容[k] = Array.isArray(v) ? v.map(读文件) : 读文件(v);
  const 底稿 = 装配器.装(单, 协议们.执行, 进项内容, { 工作目录: 依赖.工作目录 });
  const 家 = (依赖.适配器们 || 默认适配器们())[路.harness];
  if (!家 || typeof 家.跑 !== 'function') throw new Error(`取单器：没有 ${路.harness} 的适配器`);

  // **基线一张单拍一次，跨自修轮次累计。** 真跑三号：第一轮超时被掐，盘上已有 11 个文件；第二轮重拍基线，
  // 那 11 个不再算「本轮改动」，初检判「预计产出没交」——自修越修越少。改动清单是「这张单改了什么」，不是「这一轮」。
  const 基线 = (typeof 家.拍基线 === 'function') ? 家.拍基线(依赖.工作目录) : null;
  const 跑依赖 = { ...(依赖.跑依赖 || {}), ...(基线 ? { git基线: () => 基线 } : {}) };
  let 提示 = 底稿;
  for (;;) {
    let 料;
    try {
      料 = await 家.跑(适配器.进方(单, 卷, 提示, 依赖.工作目录, { 超时ms: 依赖.超时ms }), 跑依赖);
    } catch (e) {
      单 = 状态机.迁(单, '待处理', { 操作者: '取单器', 因: `适配器炸了：${e.message}`, 时刻: 时() });
      存单(单); 记事({ 类: '炸', 单: 单.id, 因: e.message });
      return { 单, 结果: '炸' };
    }
    const 包 = 证据.攒包(料);
    存包(包);
    const 检 = 校验.初检(包, 单, 卷);
    单 = 状态机.迁(单, '初检', { 操作者: '取单器', 因: '证据包在', 产物: 包, 时刻: 时() });
    单 = 状态机.记闸(单, '初检', 检.初检, { 操作者: '领域/校验', 因: 检.违.join('；') || '机判过', 时刻: 时() });
    记事({ 类: '初检', 单: 单.id, 结果: 检.初检, 违: 检.违, 待人判: 检.待人判 });
    if (检.初检 === '通过') {
      单 = { ...单, ...算产出(单, 包) };
      单 = 状态机.迁(单, '深检', { 操作者: '取单器', 因: '初检通过', 时刻: 时() });
      存单(单);
      return { 单, 结果: '进深检', 检 };
    }
    const 次 = 状态机.自修次数(单);
    if (次 >= 上限) {
      单 = 状态机.迁(单, '待处理', { 操作者: '取单器', 因: `初检三振（自修 ${次} 次仍打回）：${检.违.join('；')}`, 时刻: 时() });
      存单(单); 记事({ 类: '三振', 单: 单.id, 违: 检.违 });
      return { 单, 结果: '三振', 检 };
    }
    单 = 状态机.迁(单, '在途', { 操作者: '取单器', 因: `初检打回，自修第 ${次 + 1} 次：${检.违.join('；')}`, 时刻: 时() });
    存单(单); 记事({ 类: '自修', 单: 单.id, 第: 次 + 1, 违: 检.违 });
    提示 = 底稿 + `\n\n## 上一轮初检打回（第 ${次 + 1} 次自修）\n${检.违.map((v) => '- ' + 说人话(v)).join('\n')}\n只补这些，别的不动。上一轮已经写在盘上的文件还在、还算数，不用重写；先把「必须交出的文件」交齐。`;
  }
}

/** 初检的违例是给机器和人看的；喂回给模型时把「timeout」这类说成它能执行的话。 */
function 说人话(违) {
  if (/没正常结束：timeout/.test(违)) return '上一轮超时被掐断了——你做得太多。这一轮只做工单要求的最小交付，先交预计产出，验证与工装不在本单范围';
  if (/没正常结束/.test(违)) return '上一轮执行没正常结束（' + 违 + '）——这一轮先把预计产出交出来，其余从简';
  return 违;
}

/** 一拍：取一张、派一张。池不改，返回新池。 */
async function 拍(池, 依赖) {
  const 取 = 取单(池, 依赖);
  if (!取.单) return { 派了: null, 因们: 取.因们, 池 };
  const r = await 派(取.单, 依赖);
  const 新池 = { ...池, 工单们: (池.工单们 || []).map((t) => (t.id === r.单.id ? r.单 : t)) };
  return { 派了: r.单.id, 结果: r.结果, 单: r.单, 检: r.检, 因们: 取.因们, 池: 新池 };
}

/** 带单飞锁的拍：上一拍没完，这一拍跳过，不叠。锁来自 内核/锁.单飞。 */
function 造循环(拍一次, 锁) {
  return Object.freeze({
    async 拍() {
      if (!锁.试()) return { 跳过: true, 因: '上一拍没完' };
      try { return await 拍一次(); } finally { 锁.放(); }
    },
  });
}

