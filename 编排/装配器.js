// 装配器.js —— 上下文包：一状态一会话，会话里装什么由这里按状态机当前格决定，模型不参与。
//
// 制作人 02:20 定的三条流程规矩里的第二条「每步新会话」住这儿：
//   上下文限制的解法不是一个长会话撑到底——第五步时第一步已经被挤出窗口了。
//   每一步开新会话，装配器把这一步要的东西打包：这张单、它的进项文件、协议里跟这一步
//   有关的那一节——其余一概不给。第三步的执行者「找不到方案」这件事不存在，
//   因为方案在他开工那一刻就在窗口里。
//
// 首版只装三样：单 + 进项内容 + 协议职责节。历史会话与记忆条目（Q9 定的后两样）
// 等 领域/记忆 建了再接——现在不假装有。
//
// 纯函数：进项文件的**内容**由调用方读好传进来（编排层能碰 fs，但装配器不碰，
// 判据喂字符串就能跑）。
'use strict';
const 协议模块 = require('../领域/协议.js');

/**
 * 装。
 * @param 单      { id, title, 性质, 职能, 进项, 正文? }
 * @param 协议    已解析的协议对象（两层）
 * @param 进项内容 { 方案?: 文本, 资产?: 文本|[文本] }  —— 调用方按 单.进项 的路径读好
 * @returns 提示词字符串
 */
function 装(单, 协议, 进项内容, 选项) {
  if (!单 || !单.id) throw new Error('装配器：没有单');
  const 声 = 协议模块.权限声明(协议);
  const o = 选项 || {};
  const 段 = [];

  段.push(`# 工单 ${单.id}${单.title ? '：' + 单.title : ''}`);
  段.push(`性质：${单.性质 || '?'}　职能：${单.职能 || '?'}`);
  // 工作目录写死在提示词里：09-04 真跑模型第一笔 Write 用了 /tmp/… 这种别的形式，写闸拒了一次
  if (o.工作目录) 段.push(`工作目录：${o.工作目录}（所有文件路径相对它写，用 Write/Edit 工具写，不要写成 /tmp/… 这类别的形式）`);
  if (单.正文) { 段.push(''); 段.push(单.正文.trim()); }
  if (单.预计产出 && Object.keys(单.预计产出).length) {
    段.push(''); 段.push('## 必须交出的文件（下游单的进项指着它们，路径一字不差）');
    for (const [k, v] of Object.entries(单.预计产出)) for (const 路 of (Array.isArray(v) ? v : [v])) 段.push(`- ${k}：${路}`);
  }

  // 进项：按签名要什么装什么，装的是**内容**不是路径——执行者不找
  const 进 = 进项内容 || {};
  const 有进 = Object.keys(进).filter((k) => 进[k] !== undefined && 进[k] !== null);
  if (有进.length) {
    段.push(''); 段.push('## 进项（已放在这里，不用去找）');
    for (const k of 有进) {
      const v = Array.isArray(进[k]) ? 进[k] : [进[k]];
      v.forEach((文, i) => { 段.push(''); 段.push(`### ${k}${v.length > 1 ? ' ' + (i + 1) : ''}`); 段.push(String(文).trim()); });
    }
  }

  // 协议：**只装职责权限层**，人格语气不进执行卷（Q7）
  段.push(''); 段.push('## 本席职责与边界');
  段.push(`职能：${声.职能}`);
  段.push(`可碰目录：${声.可碰目录.join('、') || '（无，只读）'}`);
  段.push(`可用工具：${声.可用工具.join('、')}`);
  if (声.禁.length) 段.push(`禁：${声.禁.join('、')}`);

  // 完成的定义写死：交什么、不交什么
  段.push(''); 段.push('## 交付');
  段.push(交付说明(单.性质));
  段.push('不许自己判定「做完了」——做完与否由证据包过闸决定。不许改工单状态。');

  return 段.join('\n') + '\n';
}

function 交付说明(性质) {
  switch (性质) {
    case '新建': return '产出一份资产（文件）。回执写清改了哪些文件、为什么这样做。';
    case '修复': return '修改进项里的资产，并交一条能红的判据（test/ 下）。回执写清案源与修法。';
    case '调研': return '产出一份方案（md）：至少两条路线、各自取舍、你推荐哪条。';
    case '装配': return '把进项的方案与资产整合成可验收的成果。回执写清怎么验。';
    default: return '按单办。';
  }
}

module.exports = { 装, 交付说明 };
