const 格表 = Object.freeze({
  待跑: ['待派', '待重派', '已排期'],
  在途: ['在途', '初检', '深检', '仲裁'],
  候验收: ['完成'],
  已落袋: ['归档'],
  人闸: ['待审', '待处理'],
  结束: ['挂起', '废弃'],
});

/** 把状态计数归格，并把没归格的态原样报出来——加第十四态时判据会红，不会静默漏。 */
function 分格(计数) {
  const c = (计数 && typeof 计数 === 'object') ? 计数 : {};
  const 出 = { 漏: [] };
  const 归 = new Set();
  for (const 格 of Object.keys(格表)) {
    let n = 0;
    for (const 态 of 格表[格]) { n += Number(c[态]) || 0; 归.add(态); }
    出[格] = n;
  }
  for (const 态 of Object.keys(c)) if (!归.has(态)) 出.漏.push(态);
  return 出;
}

