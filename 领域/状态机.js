// ── 产出类型与人判 ────────────────────────────────────────────────
//
// 产出类型**只由性质推**（制作人 09-04 10:17：「产出类型一定是由工单性质定的」）。
// 修复只修资产（丁-1：方案要改走调研），所以四种性质各对一型，没有二义。
const 性质产出 = Object.freeze({ 新建: '资产', 修复: '资产', 调研: '方案', 装配: '成果' });
function 产出类型(单) { return (单 && 性质产出[单.性质]) || null; }

/** 职能类别在这两类里的单，制作人都要看（丁-3）。 */
const 人判类别 = Object.freeze(['美术', '策划']);

/**
 * 这张单为什么要人判；不要人判返回 null。
 * 三个触发条件任一即要：产出是方案或成果 / 职能类别是美术或策划 / 单.保留 为真。
 * 推不出产出类型（性质缺失或不认识）也要——**失效方向是拦，不是放。**
 */
function 人判因(单) {
  if (!单) return '没有单';
  const 型 = 产出类型(单);
  if (!型) return `性质「${单.性质}」推不出产出类型`;
  if (型 === '方案' || 型 === '成果') return `产出是${型}`;
  if (单.保留 === true) return '单标了保留';
  const 行 = 职能表.表.find((r) => r.名 === 单.职能);
  if (行 && 人判类别.includes(行.类别)) return `职能「${单.职能}」类别是${行.类别}`;
  return null;
}
function 要人判(单) { return 人判因(单) !== null; }

// ── 闸序列：成单时编一次，冻结带哈希 ─────────────────────────────
//
// 仲裁不预写——它是争议才有的加项，走仲裁路时代替深检的裁决。
const 闸序列算法版本 = 1;

/** 算这张单该过哪几道闸。纯函数，同一张单算多少次都一样（哈希才能当防漂的依据）。 */
function 算闸序列(单) {
  const 因 = 人判因(单);
  const 闸 = ['初检', '深检'];
  if (因) 闸.push('人判');
  const 料 = JSON.stringify({ v: 闸序列算法版本, 性质: 单 && 单.性质, 职能: 单 && 单.职能, 保留: !!(单 && 单.保留), 闸 });
  const 哈希 = crypto.createHash('sha256').update(料).digest('hex').slice(0, 16);
  return Object.freeze({ 闸: Object.freeze(闸), 因: 因 || '', 签: 因 ? '制作人' : '', 算法版本: 闸序列算法版本, 哈希 });
}

/** 编上单：成单时（校验单过、进待审前）由代码调一次；项管改了 保留 也由代码重调。返回新对象。 */
function 编闸序列(单) { return { ...单, 闸序列: 算闸序列(单) }; }

/** 冻结的序列跟现行规则对不上了（职能类别改了、保留改了没重编、没编过）。 */
function 序列漂了(单) {
  const 序 = 单 && 单.闸序列;
  if (!序 || !序.哈希) return true;
  return 序.哈希 !== 算闸序列(单).哈希;
}

// ── 闸与履历 ──────────────────────────────────────────────────────
//
// 每道闸出结果就记一条履历 {t, 闸, 结果, 操作者, 因}；状态迁移另记一条 {t, 从, 到, 因, 操作者}。
// 一条一事件，操作者与时刻各归各；「深检过了、等人判」这种中间态也有地方记。
// 闸结果的词汇与说明书一致：通过 | 打回 | 上呈。
const 闸们 = Object.freeze(['初检', '深检', '人判', '仲裁']);
const 闸结果们 = Object.freeze(['通过', '打回', '上呈']);

class 迁移拒绝 extends Error {
  constructor(msg, 从, 到) { super(msg); this.code = '迁移拒绝'; this.从 = 从; this.到 = 到; }
}

/** 记一道闸的结果。返回新对象，不改传入的单。 */
function 记闸(单, 闸, 结果, 凭) {
  const 态 = 单 && 单.状态;
  if (!闸们.includes(闸)) throw new 迁移拒绝(`「${闸}」不是闸（${闸们.join('/')}）`, 态, 态);
  if (!闸结果们.includes(结果)) throw new 迁移拒绝(`闸结果「${结果}」不是 ${闸结果们.join('/')} 之一`, 态, 态);
  const p = 凭 || {};
  if (!p.操作者) throw new 迁移拒绝(`记${闸}：没写操作者——履历上不许有无名的闸`, 态, 态);
  const 条 = { t: p.时刻 || null, 闸, 结果, 操作者: p.操作者, 因: p.因 || '' };
  return { ...单, 履历: [...(单.履历 || []), 条] };
}

/** 本轮履历：最近一次进「在途」之后的那一段。自修回在途后，上一轮的 初检:通过 不再算数。 */
function 本轮履历(单) {
  const h = (单 && 单.履历) || [];
  let 起 = 0;
  h.forEach((x, i) => { if (x.到 === '在途') 起 = i + 1; });
  return h.slice(起);
}

/** 本轮里这道闸最后一次的结果是不是 通过。后来的 打回 会盖掉先前的 通过。 */
function 闸过了(单, 闸) {
  const 本 = 本轮履历(单).filter((x) => x.闸 === 闸);
  return 本.length > 0 && 本[本.length - 1].结果 === '通过';
}

/**
 * 进「完成」还缺什么。**只读工单上冻结的闸序列**，不临时重算该不该人判。
 * @param 替  走仲裁路：仲裁的裁决代替深检
 */
function 完成缺什么(单, 替) {
  const 序 = 单 && 单.闸序列;
  if (!序 || !Array.isArray(序.闸)) return '工单上没有闸序列——成单时没编，不许完成';
  if (序列漂了(单)) return '闸序列与现行规则不一致（哈希不符）——重编或人裁，不许静默按旧的走';
  const 需 = [替 ? '仲裁' : '深检', ...(序.闸.includes('人判') ? ['人判'] : [])];   // 初检在 初检→深检 那条边上已经要过了
  for (const 闸 of 需) {
    if (闸过了(单, 闸)) continue;
    return 闸 === '人判' ? `${序.因}，要人判过才完成` : `本轮履历里没有 ${闸}:通过，不完成`;
  }
  return null;
}

// ── 迁移 ──────────────────────────────────────────────────────────
//
// **哪些边要凭据。** 不是所有迁移都要——人闸迁移（待审→待派）凭的是人的动作，
// 那由闸模块记「操作者」。要凭据的是「模型干完活」那几条：
//   在途 → 初检     要 产物（证据包）——没证据包不算干完
//   初检 → 深检     本轮履历里要有 初检:通过
//   深检 → 完成     工单上的闸序列没漂；本轮履历里要有 深检:通过；序列里有人判的还要有 人判:通过
//   仲裁 → 完成     同上，仲裁:通过 代替 深检:通过
// 这四条就是「闸序列 = [初检]+[深检]+(要人判?[人判])+(争议?[仲裁])」在代码里的形态。
const 要凭 = Object.freeze({
  '在途→初检': (凭) => 凭.产物 ? null : '进初检要证据包（产物），没有等于没干完',
  '初检→深检': (凭, 单) => 闸过了(单, '初检') ? null : '本轮履历里没有 初检:通过，不进深检',
  '深检→完成': (凭, 单) => 完成缺什么(单, false),
  '仲裁→完成': (凭, 单) => 完成缺什么(单, true),
});

/**
 * 迁移。返回**新对象**，不改传进来的单（纯函数）。
 *
 * @param 单   { 状态, 性质, 职能, 保留?, 闸序列?, 履历?, ... }
 * @param 到   目标态
 * @param 凭   { 产物?, 操作者, 因?, 时刻? }
 *
 * **凭 里没有「模型说可以」这个字段，永远不会有；闸结果也不从这里进，走 记闸()。**
 */
function 迁(单, 到, 凭) {
  const 从 = 单 && 单.状态;
  if (!状态们.includes(从)) throw new 迁移拒绝(`当前态「${从}」不是十三态之一`, 从, 到);
  if (!状态们.includes(到)) throw new 迁移拒绝(`目标态「${到}」不是十三态之一`, 从, 到);
  if (!转移[从].includes(到)) throw new 迁移拒绝(`不许从「${从}」到「${到}」`, 从, 到);
  const k = `${从}→${到}`;
  const p = 凭 || {};
  if (要凭[k]) {
    const 因 = 要凭[k](p, 单);
    if (因) throw new 迁移拒绝(`${k}：${因}`, 从, 到);
  }
  if (!p.操作者) throw new 迁移拒绝(`${k}：没写操作者——履历上不许有无名迁移`, 从, 到);
  const 条 = { t: p.时刻 || null, 从, 到, 因: p.因 || '', 操作者: p.操作者 };
  return { ...单, 状态: 到, 履历: [...(单.履历 || []), 条] };
}

/** 从履历数出来的东西——不另存字段（一个事实一处）。 */
function 自修次数(单) {
  return (单.履历 || []).filter((x) => x.到 === '在途' && (x.从 === '初检' || x.从 === '深检')).length;
}

