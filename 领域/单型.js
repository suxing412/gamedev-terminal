// 单型.js —— 类型系统的校验器：按 docs/单型/ 五份 schema 判一张单、一个专项拆得对不对。
//
// **纯函数。** 领域层禁 fs——schema 用 require 静态载入（模块加载那一刻读一次，之后没有 I/O），
// 「盘上有没有这个文件」「同专项里还有哪些单」「归属指向的东西在不在」都由调用方传进来。
// 这样判据喂假数据就能跑，变异台打得动。
//
// 它判的是**拆单判据五条**里能在 schema 层判的四条（① ② ④ ⑤）。
// 第 ③ 条「进项未过闸不派」是取单器的活，不在这儿——那要看别的单的闸结果，schema 看不到。
//
// 这是**派前**校验（拆单判据：项管拆完，机器判拆得对不对）。执行后才有的东西（产出、防复发判据）
// 不在这儿要——2026-09-04 评审甲-2：修复单的防复发判据是执行者交的「出」项，派前要它等于修复单永远派不出去。
// 执行后那一侧由 领域/校验.初检 对证据包判。
'use strict';
const 职能表 = require('../docs/单型/职能.json');
const 管线S = require('../docs/单型/管线.json');
const 特性S = require('../docs/单型/特性.json');
const 专项S = require('../docs/单型/专项.json');
const 工单S = require('../docs/单型/工单.json');
const 状态机 = require('./状态机.js');

const 性质们 = Object.freeze(Object.keys(工单S.性质签名));
const 产出三型 = Object.freeze(['方案', '资产', '成果']);

/** 性质签名：进/出 各是什么。 */
function 签名(性质) {
  const s = 工单S.性质签名[性质];
  return s ? { 进: [...s.进], 出: [...s.出] } : null;
}

/** 启用的职能行。 */
function 职能(名) {
  return 职能表.表.find((r) => r.名 === 名 && r.启用 !== false) || null;
}

/**
 * 剥：按 schema 的「谁写」列，只留这个角色能写的字段（丁-7）。
 * 白名单：表里没有的字段、谁写里没有这个角色的字段，一律剥掉——项管入口只收项管该写的，
 * 代码写的字段（状态、履历、产出）由入口剥掉，谁也别想手填一条履历。
 * 这里只是纯函数；入口必经它这件事由 待建 取单器 的判据盯。
 */
function 剥(对象, 角色, 字段表) {
  const 表 = 字段表 || 工单S.字段;
  const 出 = {};
  for (const [名, 定] of Object.entries(表)) {
    if (对象 == null || 对象[名] === undefined) continue;
    const 谁 = String(定.谁写 || '').split('/').map((s) => s.trim()).filter(Boolean);
    if (谁.includes(角色)) 出[名] = 对象[名];
  }
  return 出;
}

// ── 字段级：必填、枚举、格式、默认 ────────────────────────────────
function 验字段(对象, 字段表, 是, 选项) {
  const 违 = [];
  const 不要求谁写 = (选项 && 选项.不要求谁写) || null;   // 草稿期：代码要写的字段还没写，不算缺
  for (const [名, 定] of Object.entries(字段表)) {
    const v = 对象[名];
    const 缺 = v === undefined || v === null || v === '';
    if (缺 && 定.默认 !== undefined) continue;             // 有默认的缺省不算缺（U25）：省略 规模/优先级 不红
    if (缺 && 不要求谁写 && String(定.谁写 || '').split('/').includes(不要求谁写)) continue;
    if (定.必填 === true && 缺) { 违.push(`${是}缺必填字段「${名}」`); continue; }
    if (缺) continue;
    if (定.类型 === 'enum' && !定.合法值.includes(v)) 违.push(`${是}.${名}=「${v}」不在合法值 ${定.合法值.join('/')} 里`);
    if (定.格式 && typeof v === 'string' && !new RegExp(定.格式).test(v)) 违.push(`${是}.${名}=「${v}」不合格式 ${定.格式}`);
    if (定.类型 === 'bool' && typeof v !== 'boolean') 违.push(`${是}.${名} 该是布尔`);
    if (定.类型 === 'list' && !Array.isArray(v)) 违.push(`${是}.${名} 该是数组`);
  }
  return 违;
}

// ── 工单 ──────────────────────────────────────────────────────────
//
// 上下文 = {
//   存在(路径) → bool                 盘上有没有这个文件（调用方查，这里不碰 fs）
//   同专项单们: [单]                   同一专项里的其它单（带 创建时间 才判得出「更早」）
//   专项(id) → 专项对象 | null         归属指向的专项在不在
//   特性(id) → 特性对象 | null         归属指向的特性在不在、是不是散单
// }
function 校验单(单, 上下文) {
  const 违 = [];
  const 上 = 上下文 || {};
  const 存在 = typeof 上.存在 === 'function' ? 上.存在 : () => true;

  // 没有状态 = 草稿（项管拆完还没成单）：谁写=代码 的字段（id/状态/时间/闸序列）还没写，不算缺
  违.push(...验字段(单, 工单S.字段, '工单', 单.状态 ? null : { 不要求谁写: '代码' }));

  // ⑤ 职能 × 性质：性质必须在该职能的 可接性质 里（制作人 09-04：把性质写进职能权限）
  const 行 = 单.职能 ? 职能(单.职能) : null;
  if (单.职能 && !行) 违.push(`职能「${单.职能}」不在职能表里，或未启用`);
  if (单.性质 && !性质们.includes(单.性质)) 违.push(`性质「${单.性质}」不是四种之一（${性质们.join('/')}）`);
  if (行 && 单.性质 && 性质们.includes(单.性质)) {
    const 可 = Array.isArray(行.可接性质) ? 行.可接性质 : [];
    if (!可.includes(单.性质)) 违.push(`职能「${单.职能}」不接「${单.性质}」单（可接：${可.join('/') || '无'}）——拆单判据⑤`);
  }

  // ① 归属二选一，且指向的东西得在（U4）
  const 归 = 单.归属 || {};
  const 有专项 = !!归.专项; const 有特性 = !!归.特性;
  if (有专项 === 有特性) {
    违.push(有专项 ? '归属不许同时填 专项 和 特性' : '归属为空：要么挂专项，要么挂散单特性');
  } else if (有专项) {
    if (typeof 上.专项 === 'function' && !上.专项(归.专项)) 违.push(`归属指向的专项「${归.专项}」不存在`);
  } else {
    const 查 = typeof 上.特性 === 'function';
    const f = 查 ? 上.特性(归.特性) : undefined;
    if (查 && !f) 违.push(`归属指向的特性「${归.特性}」不存在`);
    else if (f && f.散单 !== true) 违.push(`归属直接挂了具名特性「${归.特性}」——只许挂散单特性，具名特性下面要立专项`);
  }

  // 进项按签名：要的得有（② 存在或同专项更早的单产出）、不要的不许有（U7）
  const 签 = 签名(单.性质);
  if (签) {
    const 进 = 单.进项 || {};
    const 许 = [];
    for (const 要 of 签.进) {
      const 可选 = 要.endsWith('?');
      const 候 = 要.replace('?', '').replace('[]', '').split('|');   // '资产|方案' → ['资产','方案']
      许.push(...候);
      const 有 = 候.some((k) => 进[k] !== undefined && 进[k] !== null && 进[k] !== '');
      if (!有 && !可选) { 违.push(`性质「${单.性质}」要进项 ${候.join('或')}，没填`); continue; }
      for (const k of 候) {
        const v = 进[k]; if (v === undefined || v === null || v === '') continue;
        const 路们 = Array.isArray(v) ? v : [v];
        for (const 路 of 路们) {
          if (!存在(路) && !产于同专项更早的单(路, 上.同专项单们, 单)) {
            违.push(`进项 ${k}=「${路}」既不在盘上，也不是同专项里更早的单产出的`);
          }
        }
      }
    }
    for (const k of Object.keys(进)) {
      if (!许.includes(k)) 违.push(`性质「${单.性质}」的签名不要进项 ${k}，却填了——装配器会照塞，执行者会照读`);
    }
  }

  // 状态只认状态机
  if (单.状态 && !状态机.状态们.includes(单.状态)) 违.push(`状态「${单.状态}」不是状态机十三态之一`);

  // 成单后的单（有状态的）必须带闸序列，且与现行规则一致（制作人 09-04 23:51 定：成单时编，冻结带哈希）
  if (单.状态) {
    if (!单.闸序列) 违.push('成单后的单必须带 闸序列（成单时由代码 状态机.编闸序列 编上，冻结带哈希）——没有等于没成单');
    else if (状态机.序列漂了(单)) 违.push('闸序列与现行规则不一致（哈希不符）——职能类别或保留改了没重编');
  }

  return { 行: 违.length === 0, 违 };
}

/** 「更早」按 创建时间 比（U13）；两边都没时间戳时按数组顺序算它更早（调用方按创建时间序传）。 */
function 产于同专项更早的单(路, 单们, 本单) {
  if (!Array.isArray(单们)) return false;
  return 单们.some((s) => {
    if (s.创建时间 && 本单 && 本单.创建时间 && !(s.创建时间 < 本单.创建时间)) return false;
    const 出 = s.产出 || {};
    return Object.values(出).some((v) => (Array.isArray(v) ? v : [v]).includes(路));
  });
}

// ── 专项 ──────────────────────────────────────────────────────────
//
// ④ 末单规则：最后一张子单的性质所产出的类型 == 专项.产出类型。产出类型只由性质推（状态机.产出类型）。
// 只在 收口/关账 判（U24）：拆到一半的专项末单本来就不是末单。
const 末单产出类型 = (单) => 状态机.产出类型(单);
const 判末单的态 = Object.freeze(['收口', '关账']);

function 校验专项(专项, 子单们) {
  const 违 = [];
  违.push(...验字段(专项, 专项S.字段, '专项'));
  if (专项.产出类型 && !产出三型.includes(专项.产出类型)) 违.push(`专项.产出类型「${专项.产出类型}」不是三型之一`);
  if (专项.管线) 违.push('专项不许写 管线（祖父，从 特性 推）——H107');
  const 子 = Array.isArray(子单们) ? 子单们 : [];
  if (子.length && 判末单的态.includes(专项.状态)) {
    const 末 = 子[子.length - 1];
    const 型 = 末单产出类型(末);
    if (专项.产出类型 && 型 && 型 !== 专项.产出类型) {
      违.push(`末单「${末.id || '?'}」是${末.性质}，产出${型}；专项要的是${专项.产出类型}。产出=成果的专项末单必须是装配`);
    }
  }
  return { 行: 违.length === 0, 违 };
}

// ── 特性 / 管线 ───────────────────────────────────────────────────
function 校验特性(特性) {
  const 违 = 验字段(特性, 特性S.字段, '特性');
  if (特性.挂载凭据) 违.push('特性不许存 挂载凭据（反向边）——从工单归属推');
  return { 行: 违.length === 0, 违 };
}

/** 特性们 给了才判「每条管线有且只有一个散单特性」（U5）；不给只判字段。 */
function 校验管线(管线, 特性们) {
  const 违 = 验字段(管线, 管线S.字段, '管线');
  if (Array.isArray(特性们)) {
    const n = 特性们.filter((f) => f && f.管线 === 管线.id && f.散单 === true).length;
    if (n !== 1) 违.push(`管线「${管线.id}」有 ${n} 个散单特性，规矩是有且只有一个`);
  }
  return { 行: 违.length === 0, 违 };
}

