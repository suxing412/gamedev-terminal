// 校验.js —— 机判初检：闸序列第一道。零 token、纯函数、可复现。
//
// 它判的是**形状与最低事实**，不判内容质量（那是深检的活）：
//   ① 证据包过 内核/证据.验包（六项必有、契约版本对）
//   ② 回执非空
//   ③ 按性质：新建/修复/装配 必须有改动（改动清单空 = 什么都没交）；调研 必须产出方案文件；
//      **修复的改动里必须有测试目录下的文件**——防复发判据是执行后的出项，在这儿判，不在派前判（评审甲-2）
//   ④ 改动没越过执行卷（这条是事后审计，hook 层已经拦了一次；两道都在才叫闸）
//
// 判不了的要显式说「这条只能人看」，不假装验过——所以返回里有 待人判，要不要人判问 状态机.人判因。
// 结果词汇与说明书的闸签名一致：通过 | 打回（上呈由争议路径出，这里不出）。
// 旧仓 precheck.js 有七判项（回执在位/尺寸/字段/章节/报数/逐条/禁语），这是最小版，
// 逐条对验收标准等 docs/单型 的 验收 块落了再接。
'use strict';
const 证据 = require('../内核/证据.js');
const 权限 = require('../领域/权限.js');
const 状态机 = require('../领域/状态机.js');

/**
 * @param 包     证据包
 * @param 单     { id, 性质, 职能?, 保留? }
 * @param 执行卷 领域/权限.编译执行卷 的产物（可缺省，缺省不判④）
 * @returns { 初检: '通过'|'打回', 违: [], 待人判: [] }
 */
function 初检(包, 单, 执行卷) {
  const 违 = [];
  const 待人判 = [];

  const r = 证据.验包(包);
  if (!r.行) 违.push(...r.违.map((x) => '证据包：' + x));

  if (包 && (!包.回执 || !String(包.回执).trim())) 违.push('回执为空');

  const 改 = (包 && 包.改动 && Array.isArray(包.改动.文件)) ? 包.改动.文件 : [];
  const 性 = 单 && 单.性质;
  if (性 === '新建' || 性 === '修复' || 性 === '装配') {
    if (改.length === 0) 违.push(`性质是${性}，改动清单却是空的——什么都没交`);
  }
  if (性 === '修复' && 改.length) {
    if (!改.some((f) => /(^|\/)tests?\//i.test(f))) 违.push('性质是修复，改动里没有测试目录（test/ 或 Tests/）下的文件——没有防复发判据等于没修（H104）');
  }
  if (性 === '调研') {
    if (!改.some((f) => /\.md$/i.test(f))) 违.push('性质是调研，产出里没有 .md 方案文件');
  }
  const 人判 = 状态机.人判因(单);
  if (人判) 待人判.push(`${人判}，过初检后还要人判`);

  if (执行卷 && 改.length) {
    for (const f of 改) {
      const w = 权限.准写(执行卷, f);
      if (!w.行) 违.push(`改动越界：${f}——${w.因}（hook 层该拦住的，这里是事后审计兜底）`);
    }
  }

  if (包 && 包.结果 && 包.结果.退出 !== 'completed') 违.push(`执行没正常结束：${包.结果.退出}`);

  return { 初检: 违.length === 0 ? '通过' : '打回', 违, 待人判 };
}

module.exports = { 初检 };
