// 闸.js —— 人闸注册表：谁在等谁、等多久、逾期怎么升格。
//
// 人闸有四种，全从工单/专项的状态与闸序列推出来，不另存一张「待办表」（一个事实一处）：
//   待审    工单在 待审——拆完等审批（制作人：审批只看该不该做）
//   人判    工单在 深检/仲裁、闸序列里有人判、深检（或仲裁）已通过、人判还没记——等制作人签
//   待处理  工单在 待处理——出了状况等分诊（项管）
//   关账    专项在 收口——产出是成果/方案的等制作人签，资产的项管收
// 逾期：等了超过时限 → 提醒；超过两倍 → 上呈。时限与等谁都是参数，默认表导出，可改。
//
// 纯函数。时间由调用方传 现在。
'use strict';
const 状态机 = require('./状态机.js');

const 小时 = 3600 * 1000;
const 默认时限 = Object.freeze({ 待审: 24 * 小时, 人判: 48 * 小时, 待处理: 12 * 小时, 关账: 72 * 小时 });
const 默认等谁 = Object.freeze({ 待审: '制作人', 人判: '制作人', 待处理: '项管', 关账: { 成果: '制作人', 方案: '制作人', 资产: '项管' } });

const 解 = (时) => { if (时 === undefined || 时 === null) return NaN; return typeof 时 === 'number' ? 时 : Date.parse(时); };

/** 履历里最后一次进某态的时刻。 */
function 进入时刻(单, 态) {
  const h = (单.履历 || []).filter((x) => x.到 === 态 && x.t);
  return h.length ? 解(h[h.length - 1].t) : NaN;
}
/** 履历里最后一次某闸通过的时刻。 */
function 闸通过时刻(单, 闸) {
  const h = 状态机.本轮履历(单).filter((x) => x.闸 === 闸 && x.结果 === '通过' && x.t);
  return h.length ? 解(h[h.length - 1].t) : NaN;
}

function 条目(类, 键, 等谁, 自, 现在, 时限, 注) {
  const 等了 = Number.isNaN(自) ? null : Math.max(0, 现在 - 自);
  const 逾期 = 等了 !== null && 等了 > 时限;
  const 升格 = 等了 === null ? null : 等了 > 2 * 时限 ? '上呈' : 逾期 ? '提醒' : null;
  return Object.freeze({ 类, ...键, 等谁, 自: Number.isNaN(自) ? null : new Date(自).toISOString(), 等了ms: 等了, 逾期, 升格, 注: 注 || (等了 === null ? '进入时刻不明，履历里没记 t' : '') });
}

/**
 * 在等的：所有开着的人闸。
 * @param 料   { 工单们, 专项们 }
 * @param 选项 { 现在, 时限?, 等谁? }
 */
function 在等的(料, 选项) {
  const o = 选项 || {};
  const 现在 = 解(o.现在);
  if (Number.isNaN(现在)) throw new Error('闸：要传 现在（ISO 或毫秒）——领域层不碰钟');
  const 时限 = { ...默认时限, ...(o.时限 || {}) };
  const 等谁 = { ...默认等谁, ...(o.等谁 || {}) };
  const 出 = [];
  for (const 单 of ((料 && 料.工单们) || [])) {
    if (单.状态 === '待审') 出.push(条目('待审', { 单: 单.id }, 等谁.待审, 进入时刻(单, '待审'), 现在, 时限.待审));
    else if (单.状态 === '待处理') 出.push(条目('待处理', { 单: 单.id }, 等谁.待处理, 进入时刻(单, '待处理'), 现在, 时限.待处理));
    else if (单.状态 === '深检' || 单.状态 === '仲裁') {
      const 序 = 单.闸序列;
      if (!序 || !Array.isArray(序.闸) || !序.闸.includes('人判')) continue;
      const 前闸 = 单.状态 === '仲裁' ? '仲裁' : '深检';
      if (!状态机.闸过了(单, 前闸) || 状态机.闸过了(单, '人判')) continue;
      出.push(条目('人判', { 单: 单.id }, 等谁.人判, 闸通过时刻(单, 前闸), 现在, 时限.人判, 序.因 ? `因：${序.因}` : ''));
    }
  }
  for (const 专项 of ((料 && 料.专项们) || [])) {
    if (专项.状态 !== '收口') continue;
    const 谁 = typeof 等谁.关账 === 'object' ? (等谁.关账[专项.产出类型] || '制作人') : 等谁.关账;
    出.push(条目('关账', { 专项: 专项.id }, 谁, 进入时刻(专项, '收口'), 现在, 时限.关账, 专项.产出类型 ? `产出${专项.产出类型}` : ''));
  }
  return Object.freeze(出);
}

/** 谁在等我：按角色筛。 */
function 谁在等我(料, 角色, 选项) {
  return 在等的(料, 选项).filter((x) => x.等谁 === 角色);
}

/** 汇总：按类与按人数一下，逾期与上呈单列。 */
function 汇总(在等) {
  const 出 = { 总: 在等.length, 按类: {}, 按人: {}, 逾期: [], 上呈: [] };
  for (const x of 在等) {
    出.按类[x.类] = (出.按类[x.类] || 0) + 1;
    出.按人[x.等谁] = (出.按人[x.等谁] || 0) + 1;
    if (x.逾期) 出.逾期.push(x.单 || x.专项);
    if (x.升格 === '上呈') 出.上呈.push(x.单 || x.专项);
  }
  return 出;
}

module.exports = { 默认时限, 默认等谁, 在等的, 谁在等我, 汇总 };
