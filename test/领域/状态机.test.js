// 状态机.test.js —— 十三态、归格、迁移凭据、闸履历，以及**流程自证能红**。
//
// 「假模型」那一组是这份文件存在的理由：制作人 02:17 问「模型会忘会幻觉，
// 怎么让它严格按流程走」。答案是流程住代码里、模型只做每步那一小块。
// 这组用例证明：一个只会吐垃圾、或什么都不交、或嘴上说「我做完了」、或想绕过人判的模型，
// **流程一步都不前进**。这条红不了，就说明某一步是靠模型自觉过的。
'use strict';
const assert = require('node:assert');
const test = require('node:test');
const M = require('../../领域/状态机.js');

const 凭 = (x) => ({ 操作者: '判据', 时刻: 't0', ...x });
const 闸 = (单, 名, 结果) => M.记闸(单, 名, 结果, { 操作者: 名 === '人判' ? '制作人' : '机判', 时刻: 't1' });
const 拒 = (fn, re) => assert.throws(fn, (e) => e.code === '迁移拒绝' && re.test(e.message), `该拒且理由含 ${re}`);

test('机① 十三态一个不多一个不少，核查已改名深检', () => {
  assert.strictEqual(M.状态们.length, 13);
  assert.ok(M.状态们.includes('深检'));
  assert.ok(!M.状态们.includes('核查'), '「核查」在旧仓同时指目录和两个会话，分不清，废掉');
});

test('机② 大态与归格各自覆盖全部十三态，没有漏、没有重', () => {
  for (const 表 of [M.大态, M.格表]) {
    const 见 = new Map();
    for (const [组, 态们] of Object.entries(表)) for (const t of 态们) {
      assert.ok(!见.has(t), `「${t}」同时在 ${见.get(t)} 与 ${组}`);
      见.set(t, 组);
    }
    for (const t of M.状态们) assert.ok(见.has(t), `「${t}」没归进任何组`);
  }
});

test('机③ 归格：待审/待处理 归人闸格不归待跑格；没见过的态报 漏', () => {
  const g = M.分格({ 待审: 2, 待处理: 5, 待派: 1, 新造的态: 7 });
  assert.strictEqual(g.待跑, 1);
  assert.strictEqual(g.人闸, 7);
  assert.deepStrictEqual(g.漏, ['新造的态'], '加第十四态时这里要报出来，不许静默漏');
});

test('机④ 转移表里每个目标态都是合法态，终态无出边', () => {
  for (const [从, 到们] of Object.entries(M.转移)) {
    assert.ok(M.状态们.includes(从));
    for (const 到 of 到们) assert.ok(M.状态们.includes(到), `${从}→${到}：${到} 不是态`);
  }
  assert.deepStrictEqual(M.转移.归档, []);
  assert.deepStrictEqual(M.转移.废弃, []);
});

test('机⑤ 迁() 返回新对象，不改传入的单；履历追加一条迁移条', () => {
  const 单 = { id: 'T-1', 状态: '待审', 履历: [] };
  const 新 = M.迁(单, '待派', 凭({ 因: '总监审过' }));
  assert.strictEqual(单.状态, '待审', '原对象不许被改');
  assert.strictEqual(新.状态, '待派');
  assert.strictEqual(新.履历.length, 1);
  assert.deepStrictEqual(新.履历[0], { t: 't0', 从: '待审', 到: '待派', 因: '总监审过', 操作者: '判据' });
});

test('机⑥ 不在转移表里的边被拒', () => {
  拒(() => M.迁({ 状态: '待审' }, '归档', 凭()), /不许从/);
  拒(() => M.迁({ 状态: '归档' }, '待派', 凭()), /归档/);
});

test('机⑦ 无名迁移被拒——履历上不许有没写操作者的记录', () => {
  拒(() => M.迁({ 状态: '待审' }, '待派', { 因: '试' }), /操作者/);
});

// ── 产出类型与人判 ────────────────────────────────────────────────

test('机⑧ 产出类型只由性质推：新建/修复→资产，调研→方案，装配→成果；不认识的→null', () => {
  assert.strictEqual(M.产出类型({ 性质: '新建' }), '资产');
  assert.strictEqual(M.产出类型({ 性质: '修复' }), '资产');
  assert.strictEqual(M.产出类型({ 性质: '调研' }), '方案');
  assert.strictEqual(M.产出类型({ 性质: '装配' }), '成果');
  assert.strictEqual(M.产出类型({ 性质: '评审' }), null);
  assert.strictEqual(M.产出类型({ 产出类型: '方案' }), null, '单上手填的 产出类型 不算数——那字段 schema 里没有');
});

test('机⑨ 要人判三个触发条件；推不出产出类型也要（失效方向=拦）', () => {
  assert.strictEqual(M.人判因({ 性质: '新建', 职能: '程序' }), null, '程序新建单：两闸自动完结');
  assert.match(M.人判因({ 性质: '调研', 职能: '程序' }), /方案/);
  assert.match(M.人判因({ 性质: '装配', 职能: '程序' }), /成果/);
  assert.match(M.人判因({ 性质: '新建', 职能: '原画美术' }), /美术/);
  assert.match(M.人判因({ 性质: '新建', 职能: '系统策划' }), /策划/);
  assert.match(M.人判因({ 性质: '新建', 职能: '程序', 保留: true }), /保留/);
  assert.match(M.人判因({ 职能: '程序' }), /推不出/);
  assert.match(M.人判因(null), /没有单/);
});

// ── 闸与履历 ──────────────────────────────────────────────────────

test('机⑩ 记闸 一道闸一条履历 {t, 闸, 结果, 操作者, 因}；结果只认 通过/打回/上呈；无名的拒', () => {
  const 单 = { id: 'T-7', 状态: '初检' };
  const 记 = M.记闸(单, '初检', '通过', { 操作者: '领域/校验', 时刻: 't1', 因: '六项齐' });
  assert.deepStrictEqual(记.履历, [{ t: 't1', 闸: '初检', 结果: '通过', 操作者: '领域/校验', 因: '六项齐' }]);
  assert.strictEqual(单.履历, undefined, '原对象不许被改');
  拒(() => M.记闸(单, '初检', '红', { 操作者: 'x' }), /不是 通过\/打回\/上呈/);
  拒(() => M.记闸(单, '评审', '通过', { 操作者: 'x' }), /不是闸/);
  拒(() => M.记闸(单, '初检', '通过', {}), /操作者/);
});

test('机⑪ 本轮履历：自修回在途后，上一轮的 初检:通过 不再算数', () => {
  let 单 = { id: 'T-8', 状态: '在途' };
  单 = M.迁(单, '初检', 凭({ 产物: { 包: 1 } }));
  单 = 闸(单, '初检', '通过');
  单 = M.迁(单, '在途', 凭({ 因: '深检前发现漏了，自修' }));
  单 = M.迁(单, '初检', 凭({ 产物: { 包: 2 } }));
  assert.strictEqual(M.闸过了(单, '初检'), false, '上一轮的通过不算');
  拒(() => M.迁(单, '深检', 凭()), /初检:通过/);
  单 = 闸(单, '初检', '通过');
  assert.strictEqual(M.迁(单, '深检', 凭()).状态, '深检');
});

test('机⑫ 后来的 打回 盖掉先前的 通过', () => {
  let 单 = { id: 'T-9', 状态: '初检' };
  单 = 闸(单, '初检', '通过');
  单 = 闸(单, '初检', '打回');
  assert.strictEqual(M.闸过了(单, '初检'), false);
});

// ── 流程自证能红：假模型 ──────────────────────────────────────────

test('假模型① 什么都不交（无产物）→ 进不了初检，停在在途', () => {
  const 单 = { id: 'T-2', 状态: '在途' };
  拒(() => M.迁(单, '初检', 凭({ 因: '模型说做完了' })), /证据包/);
  assert.strictEqual(单.状态, '在途', '一步没前进');
});

test('假模型② 吐垃圾当产物 → 能进初检（初检的活就是拦垃圾），但初检没过就进不了深检', () => {
  const 单 = { id: 'T-3', 状态: '在途' };
  const 进了 = M.迁(单, '初检', 凭({ 产物: { 垃圾: true } }));
  assert.strictEqual(进了.状态, '初检');
  // 履历里没有 初检:通过——模型嘴上说「通过」不算，初检打回更不算
  拒(() => M.迁(进了, '深检', 凭({ 因: '模型：我检查过了没问题' })), /初检:通过/);
  拒(() => M.迁(闸(进了, '初检', '打回'), '深检', 凭()), /初检:通过/);
});

test('假模型③ 产出是方案（调研单），深检过了但没人判 → 不许完成（人判是结构性的，不是可选的）', () => {
  let 单 = { id: 'T-4', 状态: '深检', 性质: '调研', 职能: '技术策划' };
  单 = 闸(单, '深检', '通过');
  拒(() => M.迁(单, '完成', 凭()), /要人判过/);
  const 完 = M.迁(闸(单, '人判', '通过'), '完成', 凭());
  assert.strictEqual(完.状态, '完成');
  assert.ok(完.履历.some((h) => h.闸 === '人判' && h.操作者 === '制作人'), '履历里答得出人判是谁签的');
});

test('假模型④ 程序新建单（资产），深检过了不需要人判就能完成（资产走两闸自动完结）', () => {
  const 单 = 闸({ id: 'T-5', 状态: '深检', 性质: '新建', 职能: '程序' }, '深检', '通过');
  assert.strictEqual(M.迁(单, '完成', 凭()).状态, '完成');
});

test('假模型⑤ 凭 里塞一个「模型说可以」字段，不起任何作用', () => {
  const 单 = { id: 'T-6', 状态: '在途' };
  拒(() => M.迁(单, '初检', 凭({ 模型说可以: true, 我做完了: '真的' })), /证据包/);
});

test('假模型⑥ 在途 直达 完成 / 深检 的后门不存在（丁-2）', () => {
  assert.ok(!M.转移.在途.includes('完成'), '在途→完成 是后门');
  assert.ok(!M.转移.在途.includes('深检'), '在途→深检 绕过初检');
  拒(() => M.迁({ id: 'T-10', 状态: '在途', 性质: '新建', 职能: '程序' }, '完成', 凭({ 因: '模型：全做完了' })), /不许从/);
});

test('假模型⑦ 走仲裁绕不过人判：调研单 深检→仲裁→完成 仍要 人判:通过（甲-3）', () => {
  let 单 = { id: 'T-11', 状态: '深检', 性质: '调研', 职能: '技术策划' };
  单 = M.迁(单, '仲裁', 凭({ 因: '深检有争议' }));
  单 = 闸(单, '仲裁', '通过');
  拒(() => M.迁(单, '完成', 凭()), /要人判过/);
  assert.strictEqual(M.迁(闸(单, '人判', '通过'), '完成', 凭()).状态, '完成');
});

test('假模型⑧ 美术单、策划单、标了保留的单，深检过了没人看 → 不完成（丁-3）', () => {
  for (const 单 of [
    { id: 'T-12', 状态: '深检', 性质: '新建', 职能: '原画美术' },
    { id: 'T-13', 状态: '深检', 性质: '新建', 职能: '系统策划' },
    { id: 'T-14', 状态: '深检', 性质: '新建', 职能: '程序', 保留: true },
  ]) {
    const 过深检 = 闸(单, '深检', '通过');
    拒(() => M.迁(过深检, '完成', 凭()), /要人判过/);
    assert.strictEqual(M.迁(闸(过深检, '人判', '通过'), '完成', 凭()).状态, '完成');
  }
  const 免不了 = 闸({ id: 'T-15', 状态: '深检', 性质: '新建', 职能: '原画美术', 保留: false }, '深检', '通过');
  拒(() => M.迁(免不了, '完成', 凭()), /美术/, '保留 只能往严改，填 false 免不了美术单的人判');
});

test('假模型⑨ 性质缺失或不认识 → 推不出产出类型 → 一律要人判（失效方向=拦）', () => {
  const 单 = 闸({ id: 'T-16', 状态: '深检', 职能: '程序' }, '深检', '通过');
  拒(() => M.迁(单, '完成', 凭()), /推不出/);
});

test('机⑬ 自修次数从履历数出来，不另存', () => {
  const 单 = { 状态: '在途', 履历: [
    { 从: '在途', 到: '初检' }, { 从: '初检', 到: '在途' },
    { 从: '在途', 到: '初检' }, { 从: '初检', 到: '深检' }, { 从: '深检', 到: '在途' },
  ] };
  assert.strictEqual(M.自修次数(单), 2);
});
