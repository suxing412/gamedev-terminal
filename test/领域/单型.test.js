// 单型.test.js —— 拆单判据能不能在 schema 层拦住拆错的单。
//
// 每条都是「一张拆错的单 → 违例里点名是哪条」。全部喂假数据，不碰盘：
// 「盘上有没有这个文件」由 上下文.存在 决定，判据自己定真假。
// 这是**派前**校验：执行后才有的东西（防复发判据、产出）不在这儿要。
'use strict';
const assert = require('node:assert');
const test = require('node:test');
const D = require('../../领域/单型.js');

const 好单 = (改) => ({
  id: 'TK-1', title: '试', 职能: '程序', 性质: '新建',
  归属: { 专项: 'S-1' }, 状态: '待审', 优先级: 'P1', 规模: '单兵', 项目: 'TK',
  创建时间: '2026-09-04T10:00:00Z', 更新时间: 't', ...改,
});
const 上 = (改) => ({ 存在: () => true, 同专项单们: [], 特性: () => null, ...改 });
const 违 = (r, 词) => assert.ok(r.违.some((x) => x.includes(词)), `该点名「${词}」，实得：\n  ${r.违.join('\n  ')}`);
const 过 = (r) => assert.strictEqual(r.行, true, r.违.join(' | '));

test('型① 一张拆对的新建单，过', () => {
  const r = D.校验单(好单(), 上());
  assert.deepStrictEqual(r.违, []);
  assert.strictEqual(r.行, true);
});

test('型② 五份 schema 都载进来了，四种性质签名齐；修复只修资产', () => {
  assert.deepStrictEqual(D.性质们, ['新建', '修复', '调研', '装配']);
  assert.deepStrictEqual(D.签名('装配'), { 进: ['方案', '资产[]'], 出: ['成果'] });
  assert.deepStrictEqual(D.签名('修复'), { 进: ['资产'], 出: ['资产', '防复发判据'] });
  assert.strictEqual(D.签名('评审'), null, '评审是闸不是性质');
  assert.ok(D.职能('程序'));
  assert.strictEqual(D.职能('音频'), null, '音频在表里但未启用，不算');
});

// ── ① 归属 ──
test('型③ 归属为空 → 红', () => 违(D.校验单(好单({ 归属: {} }), 上()), '归属为空'));
test('型④ 归属同时填专项和特性 → 红', () => 违(D.校验单(好单({ 归属: { 专项: 'S-1', 特性: 'F-1' } }), 上()), '不许同时'));
test('型⑤ 归属直接挂具名特性 → 红；挂散单特性 → 过', () => {
  违(D.校验单(好单({ 归属: { 特性: 'F-1' } }), 上({ 特性: () => ({ 散单: false }) })), '具名特性');
  过(D.校验单(好单({ 归属: { 特性: 'F-15' } }), 上({ 特性: () => ({ 散单: true }) })));
});

