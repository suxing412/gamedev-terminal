// 单型.test.js —— 拆单判据能不能在 schema 层拦住拆错的单。
//
// 每条都是「一张拆错的单 → 违例里点名是哪条」。全部喂假数据，不碰盘：
// 「盘上有没有这个文件」由 上下文.存在 决定，判据自己定真假。
'use strict';
const assert = require('node:assert');
const test = require('node:test');
const D = require('../../领域/单型.js');

const 好单 = (改) => ({
  id: 'TK-1', title: '试', 职能: '程序', 性质: '新建',
  归属: { 专项: 'S-1' }, 状态: '待审', 优先级: 'P1', 规模: '单兵', 项目: 'TK',
  创建时间: 't', 更新时间: 't', ...改,
});
const 上 = (改) => ({ 存在: () => true, 同专项单们: [], 特性: () => null, ...改 });
const 违 = (r, 词) => assert.ok(r.违.some((x) => x.includes(词)), `该点名「${词}」，实得：\n  ${r.违.join('\n  ')}`);

test('型① 一张拆对的新建单，过', () => {
  const r = D.校验单(好单(), 上());
  assert.deepStrictEqual(r.违, []);
  assert.strictEqual(r.行, true);
});

test('型② 五份 schema 都载进来了，四种性质签名齐', () => {
  assert.deepStrictEqual(D.性质们, ['新建', '修复', '调研', '装配']);
  assert.deepStrictEqual(D.签名('装配'), { 进: ['方案', '资产[]'], 出: ['成果'] });
  assert.strictEqual(D.签名('评审'), null, '评审是闸不是性质');
  assert.ok(D.职能('程序'));
  assert.strictEqual(D.职能('音频'), null, '音频在表里但未启用，不算');
});

// ── ① 归属 ──
test('型③ 归属为空 → 红', () => 违(D.校验单(好单({ 归属: {} }), 上()), '归属为空'));
test('型④ 归属同时填专项和特性 → 红', () => 违(D.校验单(好单({ 归属: { 专项: 'S-1', 特性: 'F-1' } }), 上()), '不许同时'));
test('型⑤ 归属直接挂具名特性 → 红；挂散单特性 → 过', () => {
  违(D.校验单(好单({ 归属: { 特性: 'F-1' } }), 上({ 特性: () => ({ 散单: false }) })), '具名特性');
  const r = D.校验单(好单({ 归属: { 特性: 'F-15' } }), 上({ 特性: () => ({ 散单: true }) }));
  assert.strictEqual(r.行, true, r.违.join(' | '));
});

// ── ⑤ 职能 × 性质 ──
test('型⑥ 职能不在表里 / 未启用 → 红', () => {
  违(D.校验单(好单({ 职能: '算命' }), 上()), '不在职能表');
  违(D.校验单(好单({ 职能: '音频' }), 上()), '未启用');
});
test('型⑦ 性质不是四种之一 → 红', () => 违(D.校验单(好单({ 性质: '评审' }), 上()), '不是四种之一'));

// ── 进项按签名 + ② 存在 ──
test('型⑧ 修复单没进项 → 红；有资产进项且盘上有 → 过', () => {
  违(D.校验单(好单({ 性质: '修复', 防复发判据: 'test/x.test.js' }), 上()), '要进项');
  const r = D.校验单(好单({ 性质: '修复', 进项: { 资产: 'Assets/A.cs' }, 防复发判据: 'test/x.test.js' }), 上());
  assert.strictEqual(r.行, true, r.违.join(' | '));
});
test('型⑨ 修复单没有防复发判据 → 红（没有等于没修）', () => {
  违(D.校验单(好单({ 性质: '修复', 进项: { 资产: 'Assets/A.cs' } }), 上()), '防复发判据');
});
test('型⑩ 装配单缺方案或缺资产 → 红', () => {
  违(D.校验单(好单({ 性质: '装配', 进项: { 资产: ['a', 'b'] } }), 上()), '要进项 方案');
  违(D.校验单(好单({ 性质: '装配', 进项: { 方案: 'm.md' } }), 上()), '要进项 资产');
});
test('型⑪ 进项指向的文件不在盘上、也不是同专项更早的单产出的 → 红', () => {
  违(D.校验单(好单({ 性质: '新建', 进项: { 方案: '方案/没有.md' } }), 上({ 存在: () => false })), '既不在盘上');
});
test('型⑫ 进项由同专项更早的单产出 → 过（数据流判据）', () => {
  const 调研 = { id: 'TK-0', 性质: '调研', 产出: { 方案: '方案/TK-0-寻路.md' } };
  const r = D.校验单(好单({ 性质: '新建', 进项: { 方案: '方案/TK-0-寻路.md' } }),
    上({ 存在: () => false, 同专项单们: [调研] }));
  assert.strictEqual(r.行, true, r.违.join(' | '));
});
test('型⑬ 新建单不带方案也过（方案是可选进项）', () => {
  assert.strictEqual(D.校验单(好单({ 性质: '新建' }), 上()).行, true);
});

// ── 状态 ──
test('型⑭ 状态不是状态机十三态 → 红', () => 违(D.校验单(好单({ 状态: '核查' }), 上()), '十三态'));

// ── ④ 专项末单规则 ──
const 专项 = (改) => ({ id: 'S-1', 名称: '试', 特性: 'F-1', 产出类型: '成果', 目标: '能跑', 状态: '进行', ...改 });
test('型⑮ 产出=成果的专项，末单是新建 → 红；末单是装配 → 过', () => {
  违(D.校验专项(专项(), [{ id: 'a', 性质: '调研' }, { id: 'b', 性质: '新建' }]), '末单必须是装配');
  assert.strictEqual(D.校验专项(专项(), [{ 性质: '调研' }, { 性质: '新建' }, { 性质: '装配' }]).行, true);
});
test('型⑯ 产出=方案的专项，末单是调研 → 过；末单是装配 → 红', () => {
  assert.strictEqual(D.校验专项(专项({ 产出类型: '方案' }), [{ 性质: '调研' }]).行, true);
  违(D.校验专项(专项({ 产出类型: '方案' }), [{ 性质: '装配' }]), '专项要的是方案');
});
test('型⑰ 专项写了 管线 → 红（祖父，H107）', () => 违(D.校验专项(专项({ 管线: 'P-1' }), []), 'H107'));
test('型⑱ 专项缺产出类型 → 红（立项必填，不许事后补）', () => 违(D.校验专项(专项({ 产出类型: undefined }), []), '产出类型'));

// ── 特性 / 管线 ──
test('型⑲ 特性存了挂载凭据 → 红（反向边）', () => {
  违(D.校验特性({ id: 'F-1', 名称: 'x', 管线: 'P-1', 边界: '管这些', 状态: '活跃', 挂载凭据: {} }), '反向边');
});
test('型⑳ 特性缺边界 → 红（它是拆单的路由键）', () => {
  违(D.校验特性({ id: 'F-1', 名称: 'x', 管线: 'P-1', 状态: '活跃' }), '边界');
});
test('型㉑ 管线三字段齐就过；状态非法红', () => {
  assert.strictEqual(D.校验管线({ id: 'P-1', 名称: '地图', 范围: '管地图', 状态: '活跃' }).行, true);
  违(D.校验管线({ id: 'P-1', 名称: '地图', 范围: '管地图', 状态: '暂停' }), '合法值');
});
