test('型㉘ 剥：按「谁写」只留这个角色能写的字段（丁-7）；表里没有的、别人写的一律剥掉', () => {
  const 脏 = { id: 'TK-1', title: 't', 职能: '程序', 状态: '完成', 履历: [{ 闸: '人判', 结果: '通过' }], 执行池: 'codex', 防复发判据: 'x', 私货: 1 };
  const 项管 = D.剥(脏, '项管');
  assert.deepStrictEqual(Object.keys(项管).sort(), ['title', '执行池', '职能'].sort(), '项管只剩它该写的');
  assert.strictEqual(项管.状态, undefined, '状态是代码写的');
  assert.strictEqual(项管.履历, undefined, '履历机器写，人不改');
  assert.strictEqual(项管.私货, undefined, '表里没有的字段剥掉');
  assert.deepStrictEqual(Object.keys(D.剥(脏, '执行者')), ['防复发判据']);
  assert.deepStrictEqual(Object.keys(D.剥(脏, '总监')), ['执行池'], '谁写=总监/项管 两个角色都能写');
});
