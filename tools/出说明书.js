// 出说明书.js —— 从 docs/模块.json 生成两样东西：
//   ① docs/说明书.md      —— 人读的总说明书
//   ② <层>/说明.md        —— 每个层目录里放一份，写清这一层装什么、能依赖谁
//
// ② 不只是为了好看：**git 不跟踪空目录**，六个层目录在 GitHub 上根本看不见。
// 制作人 2026-09-03 看着本地文件夹问「这些都什么东西」——那正是这个漏洞的症状：
// 目录存在、没有任何东西解释它，而说明书当时只写了模块、没写目录本身。
//
// **人读的那几份全是生成的，不要手改。** 手写两份必然分家，而分家的时候
// 没有任何东西会响——这正是这个仓要治的病。正本只有 JSON 那一份。
'use strict';
const fs = require('fs');
const path = require('path');

const 根 = path.join(__dirname, '..');
const 表 = JSON.parse(fs.readFileSync(path.join(根, 'docs', '模块.json'), 'utf8'));

const 别手改 = '<!-- 这份文件是 tools/出说明书.js 生成的，不要手改。正本是 docs/模块.json。 -->';

// ── ① 总说明书 ──────────────────────────────────────────────────
const 行 = [];
const 写 = (s = '') => 行.push(s);

写(别手改);
写();
写('# 游戏开发者终端 · 说明书');
写();
写('> **这份文件是生成的，不要手改。** 正本是 `docs/模块.json`，改那一份然后 `npm run 说明书`。');
写('> `test/架构/说明书.test.js` 盯着正本与代码不许分家：声明了没建会红，建了没声明也会红。');
写();
写(`> 进度：**已建 ${表.模块.length}** · 待建 ${表.待建.length} · 明确不带 ${表.不带.length}`);
写('>');
写('> **回归条件**：待建清空之日，新仓可以取代旧仓。（2026-09-02 拍板）');
写();
写('---');
写();

写('## 一、仓里都有什么');
写();
写('每一个顶层目录与文件都必须在这张表里 —— `书⑪` 盯着，加了不写会红。');
写();
// 表格单元格里的竖线必须转义：性质签名「资产|方案」曾把一行切成六格、表头多出两列空的（09-04 晨制作人抓的）。
const 格 = (s) => String(s == null ? '' : s).replace(/\|/g, '\\|');
写('| | 是什么 | 装什么 | 谁往里放东西 |');
写('|---|---|---|---|');
for (const d of (表.目录 || [])) {
  写(`| \`${d.名}\` | ${格(d.是)} | ${格(d.装什么)} | ${格(d.谁改)} |`);
}
写();

写('## 二、分层');
写();
写('依赖方向严格单向，由 `书⑨` 按**实际 require** 判红——不是按下面这张表里写的判。');
写();
写('| 层 | 目录 | 负责 | 可依赖 | 禁 |');
写('|---|---|---|---|---|');
for (const l of 表.层) {
  写(`| **${l.键}** | \`${l.目录}/\` | ${格(l.负责)} | ${(l.可依赖 || []).map((x) => '`' + x + '`').join(' ') || '—'} | ${(l.禁 || []).map((x) => '`' + x + '`').join(' ') || '—'} |`);
}
写();

// ── 类型系统（研发环的地基）──
//
// **两处真源，各管各的**：定义与道理（产出三型、闸序列、双链、方案存法）在 模块.json；
// 机器读的形状（性质签名、职能表、四层字段、拆单判据）在 docs/单型/*.json——领域/单型 require 的
// 就是那几份。09-04 晨制作人抓到性质表渲染坏之后追问「其它地方是不是也有问题」——有：
// 性质签名、拆单判据、职能十个、四层字段当时在 模块.json 里各抄了一份，措辞已经跟 docs/单型 漂开
// （拆单判据⑤ 一边写「在 class 表里存在」一边写「在表里且启用」）。现在这一节直接从 docs/单型 渲染，
// 模块.json 只留散文；书⑮ 盯着不许抄回来，书⑯ 盯着每个字段名都渲染到了。
const 单型目录 = path.join(根, 'docs', '单型');
const 读单型 = (名) => JSON.parse(fs.readFileSync(path.join(单型目录, 名 + '.json'), 'utf8'));
const 型 = 表.类型系统;
function 写字段表(S) {
  写('| 字段 | 类型 | 必填 | 谁写 | 说明 |'); 写('|---|---|---|---|---|');
  const 字段们 = Object.entries(S.字段 || {});
  for (const [名, 定] of 字段们) {
    const 类 = 定.类型
      + (定.合法值 ? `：${定.合法值.join(' / ')}` : '')
      + (定.指向 ? ` → ${定.指向}` : '')
      + (定.格式 ? `，格式 \`${定.格式}\`` : '');
    const 必 = 定.必填 === true ? '是' : 定.必填 === false ? '否' : String(定.必填);
    const 说 = (定.说明 || '') + (定.默认 !== undefined ? `（默认 ${JSON.stringify(定.默认)}）` : '');
    写(`| \`${名}\` | ${格(类)} | ${必} | ${格(定.谁写 || '')} | ${格(说)} |`);
  }
  写();
}
if (型) {
  const 工单S = 读单型('工单');
  const 职能S = 读单型('职能');
  写('## 二·五、类型系统（研发环的地基）');
  写();
  写(型.单型 || '');
  写();
  写('> 这一节有两处真源：**定义与道理**在 `docs/模块.json` 的 类型系统；**机器读的形状**（性质签名、职能表、四层字段、拆单判据）在 `docs/单型/*.json`，`领域/单型` require 的就是那几份。下面的表直接从那里渲染，`书⑮` 盯着 模块.json 不许再抄一份，`书⑯` 盯着每个字段都渲染到了。');
  写();
  写('**产出三型**');
  写();
  写('| 型 | 定义 | 验收 |'); 写('|---|---|---|');
  for (const x of (型.产出 || [])) 写(`| **${x.型}** | ${格(x.定义)} | ${格(x.验收)} |`);
  写();
  写('**性质四种（定死）**——' + ((型.性质 || {}).说明 || '') + ' 每种是一个输入→输出签名；进项之外，每张单本身总是输入，表里不再写。真源 `docs/单型/工单.json` 性质签名。');
  写();
  写('| 性质 | 进 | 出 | 说 |'); 写('|---|---|---|---|');
  const 说们 = new Map(((型.性质 || {}).表 || []).map((x) => [x.性质, x.说]));
  for (const [性质, 签] of Object.entries(工单S.性质签名 || {})) {
    写(`| **${性质}** | ${格((签.进 || []).join(' + ') || '（无）')} | ${格((签.出 || []).join(' + '))} | ${格(说们.get(性质) || '')} |`);
  }
  写();
  写('**职能（可自定义的 class）**——' + ((型.职能 || {}).说明 || '') + ' 真源 `docs/单型/职能.json`。');
  写();
  写字段表(职能S);
  写('| 职能 | 接 | 产出 | 产出属于 | 启用 | 备注 |'); 写('|---|---|---|---|---|---|');
  for (const r of (职能S.表 || [])) 写(`| **${格(r.名)}** | ${格(r.接)} | ${格(r.产出)} | ${格(r.产出属于)} | ${r.启用 === false ? '否' : '是'} | ${格(r.备注 || '')} |`);
  写();
  if ((职能S.待制作人定 || []).length) { 写('待制作人定：'); 写(); for (const q of 职能S.待制作人定) 写(`- ${q}`); 写(); }
  写('**四层 schema**——' + ((型.四层schema || {}).说明 || '') + ' 真源 `docs/单型/{管线,特性,专项,工单}.json`。');
  写();
  for (const k of ['管线', '特性', '专项', '工单']) {
    const S = 读单型(k);
    写(`#### ${k}`);
    写();
    写(S.说明 || '');
    写();
    写字段表(S);
    for (const g of (S.规矩 || [])) 写(`- ${g}`);
    if (S.归属规则) 写(`- 归属规则：${S.归属规则}`);
    if ((S.规矩 || []).length || S.归属规则) 写();
    const 删 = S.删掉的旧字段;
    if (删 && Object.keys(删).length) { 写('~~删掉的旧字段~~：' + Object.entries(删).map(([a, b]) => `${a}（${b}）`).join('；')); 写(); }
    if (S.现有) { 写('现有：' + Object.entries(S.现有).map(([a, b]) => `${a} ${Array.isArray(b) ? b.join('/') : b}`).join(' · ')); 写(); }
  }
  写('**拆单判据**（' + ((型.拆单判据 || {}).说明 || '') + '）真源 `docs/单型/工单.json` 拆单判据。');
  写();
  for (const x of (工单S.拆单判据 || [])) 写(`- ${x}`);
  写();
  if (型.闸序列) { 写('**闸序列**：`' + 型.闸序列.序列 + '`　' + (型.闸序列.说明 || '') + ' ' + (型.闸序列.分层级验收 || '')); 写(); }
  if (型.双链) { 写('**双链**：' + [型.双链.要, 型.双链.不要, 型.双链.存法, 型.双链.读取在哪].filter(Boolean).join(' ')); 写(); }
  if (型.方案存法) { 写('**方案存法**：' + [型.方案存法.存, 型.方案存法.边, 型.方案存法.怎么找到].filter(Boolean).join(' ')); 写(); }
}

写('## 三、已建');
写();
if (!表.模块.length) 写('（还没有）');
else {
  写('| 模块 | 层 | 文件 | 判据 | 负责 |');
  写('|---|---|---|---|---|');
  for (const m of 表.模块) {
    写(`| **${m.键}** | ${m.层} | \`${m.文件}\` | \`${m.判据}\` | ${格(m.负责)} |`);
  }
}
写();

写('## 四、待建');
写();
写('**这张表清空 = 新仓可以取代旧仓。** 建完一项就从这里搬到「已建」——两边都留会让这个数字失真，而这个数字是回归条件。');
写();
for (const l of 表.层) {
  const 组 = 表.待建.filter((w) => w.层 === l.键);
  if (!组.length) continue;
  写(`### ${l.键}（${组.length}）`);
  写();
  for (const w of 组) 写(`- **${w.键}** —— ${w.负责}`);
  写();
}

写('## 五、明确不带');
写();
写('旧仓里有、新仓不要的东西。写在这里是为了以后不会有人问「那个功能哪去了」。');
写();
写('| 什么 | 为什么不带 |');
写('|---|---|');
for (const n of 表.不带) 写(`| ${格(n.什么)} | ${格(n.为什么)} |`);
写();

const 总 = 行.join('\n') + '\n';
fs.writeFileSync(path.join(根, 'docs', '说明书.md'), 总, 'utf8');

// ── ② 每个层目录一份说明 ────────────────────────────────────────
// git 不跟踪空目录。层目录还没有代码时，这份说明就是它在仓里存在的唯一凭据，
// 顺带解释了它是干嘛的——没有它，clone 下来只看见一堆空文件夹。
let 份 = 0;
for (const l of 表.层) {
  const 目录 = path.join(根, l.目录);
  fs.mkdirSync(目录, { recursive: true });
  const 已建 = 表.模块.filter((m) => m.层 === l.键);
  const 待建 = 表.待建.filter((w) => w.层 === l.键);
  const s = [
    别手改,
    '',
    `# ${l.键}`,
    '',
    l.负责,
    '',
    `- **可依赖**：${(l.可依赖 || []).join(' · ') || '（不依赖任何层）'}`,
    `- **禁**：${(l.禁 || []).join(' · ') || '（无）'}`,
    `- **已建 ${已建.length} · 待建 ${待建.length}**`,
    '',
    已建.length ? '## 已建\n\n' + 已建.map((m) => `- \`${path.basename(m.文件)}\` —— ${m.负责}`).join('\n') : '',
    已建.length ? '' : '',
    待建.length ? '## 待建\n\n' + 待建.map((w) => `- **${w.键.split('/').pop()}** —— ${w.负责}`).join('\n') : '',
    '',
    '---',
    '',
    '这份说明由 `docs/模块.json` 生成。改那一份，然后 `npm run 说明书`。',
    '',
  ].filter((x) => x !== null).join('\n');
  fs.writeFileSync(path.join(目录, '说明.md'), s.replace(/\n{3,}/g, '\n\n'), 'utf8');
  份 += 1;
}

console.log(`已生成 docs/说明书.md + ${份} 份层说明（已建 ${表.模块.length} · 待建 ${表.待建.length} · 目录 ${(表.目录 || []).length} 条）`);
