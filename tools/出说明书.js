// 出说明书.js —— 从 docs/模块.json 生成 docs/说明书.md。
//
// **人读的那份是生成的，不是手写的。** 手写两份必然分家，而分家的时候
// 没有任何东西会响——这正是这个仓要治的病。正本只有 JSON 那一份。
'use strict';
const fs = require('fs');
const path = require('path');

const 根 = path.join(__dirname, '..');
const 表 = JSON.parse(fs.readFileSync(path.join(根, 'docs', '模块.json'), 'utf8'));

const 行 = [];
const 写 = (s = '') => 行.push(s);

写('# 游戏开发者终端 · 说明书');
写();
写('> **这份文件是生成的，不要手改。** 正本是 `docs/模块.json`，改那一份然后 `npm run 说明书`。');
写('> `test/架构/说明书.test.js` 盯着正本与代码不许分家：声明了没建会红，建了没声明也会红。');
写();
写(`> 进度：**已建 ${表.模块.length}** · 待建 ${表.待建.length} · 明确不带 ${表.不带.length}`);
写('>');
写('> **回归条件**：待建清空之日，新仓可以取代旧仓。（2026-09-02 拍板）');
写();
写('---');
写();

写('## 一、分层');
写();
写('依赖方向严格单向，由 `书⑨` 按**实际 require** 判红——不是按下面这张表里写的判。');
写();
写('| 层 | 目录 | 负责 | 可依赖 |');
写('|---|---|---|---|');
for (const l of 表.层) {
  写(`| **${l.键}** | \`${l.目录}/\` | ${l.负责} | ${(l.可依赖 || []).map((x) => '`' + x + '`').join(' ') || '—'} |`);
}
写();

写('## 二、已建');
写();
if (!表.模块.length) 写('（还没有）');
else {
  写('| 模块 | 层 | 文件 | 判据 | 负责 |');
  写('|---|---|---|---|---|');
  for (const m of 表.模块) {
    写(`| **${m.键}** | ${m.层} | \`${m.文件}\` | \`${m.判据}\` | ${m.负责} |`);
  }
}
写();

写('## 三、待建');
写();
写('**这张表清空 = 新仓可以取代旧仓。** 建完一项就从这里搬到「已建」——两边都留会让这个数字失真，而这个数字是回归条件。');
写();
for (const l of 表.层) {
  const 组 = 表.待建.filter((w) => w.层 === l.键);
  if (!组.length) continue;
  写(`### ${l.键}（${组.length}）`);
  写();
  for (const w of 组) 写(`- **${w.键}** —— ${w.负责}`);
  写();
}

写('## 四、明确不带');
写();
写('旧仓里有、新仓不要的东西。写在这里是为了以后不会有人问「那个功能哪去了」。');
写();
写('| 什么 | 为什么不带 |');
写('|---|---|');
for (const n of 表.不带) 写(`| ${n.什么} | ${n.为什么} |`);
写();

const 出 = 行.join('\n') + '\n';
fs.writeFileSync(path.join(根, 'docs', '说明书.md'), 出, 'utf8');
console.log(`已生成 docs/说明书.md（${出.length} 字符 · 已建 ${表.模块.length} · 待建 ${表.待建.length}）`);
