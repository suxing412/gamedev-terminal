// 出评审稿.js —— 生成一份**给制作人手改**的功能清单。
//
// 为什么不直接改 docs/说明书.md：那一份是生成的，判据 书⑬ 盯着它与正本一致，
// 手改会当场红。所以另开一份一次性的评审稿：
//
//   出稿 → 制作人在上面改 → 我读一遍给反馈 → 并进 docs/模块.json（正本）→ 这份作废
//
// **它不在 书⑬ 的比对名单里**，因为它就是要被手改的。这一点是有意的，
// 不是漏了——生成物与工作稿是两种东西，混在一起就会出现「改哪份都不对」。
'use strict';
const fs = require('fs');
const path = require('path');

const 根 = path.join(__dirname, '..');
const 表 = JSON.parse(fs.readFileSync(path.join(根, 'docs', '模块.json'), 'utf8'));
const 功能 = 表.功能 || [];

const 行 = [];
const 写 = (s = '') => 行.push(s);

写('# 功能清单 · 待制作人过目');
写();
写(`> 生成自 \`docs/模块.json\`，共 **${功能.length} 条**。`);
写('> **这份是一次性工作稿，可以随便改。** 正本是那份 JSON，改完我并进去，这份就作废。');
写();
写('## 怎么改');
写();
写('| 你想干什么 | 怎么写 |');
写('|---|---|');
写('| 删掉这条功能 | 标题行末尾加 `【删】` |');
写('| 改文字 | 直接改，格式乱了没关系 |');
写('| 这条我看过没问题 | 标题行末尾加 `【过】` |');
写('| 拿不准 / 有疑问 | 在那条下面另起一行写 `?? 你的问题` |');
写('| 想加新功能 | 拉到最后「三、我要加的」，照模板写 |');
写('| 优先级 | 标题行末尾加 `【先做】` 或 `【以后】` |');
写();
写('标记可以叠加，比如 `【过】【先做】`。');
写();
写('## 每条在说什么');
写();
写('- **给谁** —— 这个功能是给哪个角色用的');
写('- **能干什么** —— 从你的角度，你能拿它做什么');
写('- **凭什么算做完** —— **这条最要紧**。它是验收标准，要能照着做一遍。');
写('  写不出这么一句，说明这个功能还没想清楚，就不该开工。**这一条我最想听你的意见。**');
写('- ~~靠~~ —— 零件，你不用管，我留在这儿只是为了自己对账');
写();
写('---');
写();

const 分组 = [
  ['一、旧终端带过来的', (f) => f.来源 === '旧终端'],
  ['二、监制台带过来的', (f) => String(f.来源).startsWith('监制台')],
  ['三、两边都有 / 其它', (f) => f.来源 !== '旧终端' && !String(f.来源).startsWith('监制台')],
];

let n = 0;
for (const [标题, 筛] of 分组) {
  const 组 = 功能.filter(筛);
  if (!组.length) continue;
  写(`# ${标题}（${组.length} 条）`);
  写();
  for (const f of 组) {
    n += 1;
    写(`## ${n}. ${f.名}`);
    写();
    写(`- **给谁**：${f.给谁}`);
    写(`- **能干什么**：${f.能干什么}`);
    写(`- **凭什么算做完**：${f.凭什么算做完}`);
    写(`- <sub>来源：${f.来源} ｜ 靠：${(f.靠 || []).join(' · ')}</sub>`);
    写();
  }
  写('---');
  写();
}

写('# 四、我要加的');
写();
写('照下面这个模板往下写，写几条都行。写不全没关系——「凭什么算做完」想不出来就先空着，');
写('那本身就是有用的信号：说明这个功能还没想清楚，我们可以一起把它问清楚。');
写();
写('```');
写('## 功能名');
写('');
写('- 给谁：');
写('- 能干什么：');
写('- 凭什么算做完：');
写('```');
写();
写('---');
写();
写('# 五、我想说的别的');
写();
写('（这里随便写。缺什么、多什么、哪条描述不对、顺序该怎么排——都写这儿。）');
写();
写();
写();

const 出 = 行.join('\n') + '\n';
const 目标 = path.join(根, 'docs', '功能清单-评审稿.md');
fs.writeFileSync(目标, 出, 'utf8');
console.log(`已生成 docs/功能清单-评审稿.md（${功能.length} 条 · ${出.length} 字符）`);
console.log('这份可以随便改。改完告诉我，我读一遍给反馈，然后并进 docs/模块.json。');
