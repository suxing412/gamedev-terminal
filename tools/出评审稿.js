// 出评审稿.js —— 生成一份**给制作人手改**的系统清单。
//
// 为什么不直接改 docs/说明书.md：那一份是生成的，判据 书⑬ 盯着它与正本一致，
// 手改会当场红。所以另开一份一次性的评审稿：
//
//   出稿 → 制作人在上面改 → 我读一遍给反馈 → 并进 docs/模块.json（正本）→ 这份作废
//
// **它不在 书⑬ 的比对名单里**，因为它就是要被手改的。生成物与工作稿是两种东西，
// 混在一起就会出现「改哪份都不对」。
//
// 2026-09-03 改版：顶层从「功能」换成「系统」。制作人原话：
// 「我想要的是系统是系统，能自己闭环的系统，不是这种碎片化的功能」。
'use strict';
const fs = require('fs');
const path = require('path');

const 根 = path.join(__dirname, '..');
const 表 = JSON.parse(fs.readFileSync(path.join(根, 'docs', '模块.json'), 'utf8'));
const 系统 = 表.系统 || [];
const 外 = 表.系统之外 || [];

const 行 = [];
const 写 = (s = '') => 行.push(s);

写('# 系统清单 · 待制作人过目');
写();
写(`> **${系统.length} 个系统**，另有 ${外.length} 项还没归位。`);
写('> 这份稿子是照你 2026-09-03 口述的六条整理的，**没有替你补词**——');
写('> 我不懂的地方都摆在每个系统下面的「?? 我不懂的」里，没有猜。');
写('>');
写('> **这份是一次性工作稿，随便改。** 正本是 `docs/模块.json`，改完我并进去，这份作废。');
写();
写('## 怎么改');
写();
写('| 你想干什么 | 怎么写 |');
写('|---|---|');
写('| 答我的问题 | 在 `??` 那一行下面直接写答案 |');
写('| 改这一圈的步骤 | 直接改那个列表，加减都行 |');
写('| 这个系统没了 | 标题行末尾加 `【删】` |');
写('| 这个系统我看过了没问题 | 标题行末尾加 `【过】` |');
写('| 先做哪个 | 标题行末尾加 `【1】``【2】``【3】`…… |');
写('| 加一个系统 | 拉到最后照模板写 |');
写();
写('---');
写();
写('## 先说清楚「系统」和「功能」的差别');
写();
写('- **系统**＝能自己转起来的一圈。缺一节就是死的。');
写('- **功能**＝环上的某一节。比如「查一张单」「排期」「选厂」「验收」全在研发那一个环上。');
写();
写('所以验收标准也不一样：');
写();
写('- 功能式：「顶条能显示待拍板数」← 做完了，但可能没用');
写('- 闭环式：**「说一句需求，之后不碰它，最后收到可验收的产出」** ← 这句成立，整条线才算活');
写();
写('**每个系统下面的「凭什么算闭上了」就是这一句。这一栏我最想听你的意见。**');
写();
写('---');
写();

const 档标 = { 已闭环: '✅ 已闭环', 在建: '🔨 在建', 已声明未设计: '❓ 一定要有，还没想好怎么做' };

系统.forEach((s, i) => {
  写(`# ${i + 1}. ${s.名}`);
  写();
  写(`**状态**：${档标[s.状态] || s.状态}　　<sub>来源：${s.来源 || '—'}</sub>`);
  写();

  if (s.状态 === '已声明未设计') {
    写('**为什么一定要有**：' + s.为什么一定要有);
    写();
  } else {
    写('**这一圈怎么转**：');
    写();
    写('```');
    写(s.这一圈.join('  →  '));
    写('```');
    写();
    写(`**人在哪一步介入**：${(s.人在哪介入 || []).join(' / ') || '（没写）'}`);
    写();
    写(`**凭什么算闭上了**：${s.凭什么算闭上了}`);
    写();
  }

  if ((s.待明确 || []).length) {
    写('**?? 我不懂的（请在每条下面直接写答案）**：');
    写();
    for (const q of s.待明确) {
      写(`?? ${q}`);
      写();
      写('> ');
      写();
    }
  }

  写(`<sub>靠：${(s.靠 || []).join(' · ') || '（还没有零件）'}　←　零件，你不用管</sub>`);
  写();
  写('---');
  写();
});

if (外.length) {
  写('# 还没归位的');
  写();
  写('这些东西**真实存在**，但你给的系统清单里没有它。');
  写('我没有硬塞进某个系统——硬塞就是我替你做决定。');
  写();
  for (const x of 外) {
    写(`## ${x.什么}`);
    写();
    写(`- **现状**：${x.现状}`);
    写(`- **为什么单列**：${x.为什么单列}`);
    写();
    写(`?? ${x.待明确}`);
    写();
    写('> ');
    写();
  }
  写('---');
  写();
}

写('# 我要加的系统');
写();
写('照这个模板往下写，写几个都行：');
写();
写('```');
写('## 系统名');
写('');
写('这一圈怎么转：A → B → C → D');
写('人在哪一步介入：');
写('凭什么算闭上了：');
写('```');
写();
写('**「凭什么算闭上了」想不出来就先空着。** 空着是有用的信号——');
写('说明这一圈还没想清楚，我们可以一起把它问清楚，而不是先建了再说。');
写();
写('---');
写();
写('# 我想说的别的');
写();
写('（顺序该怎么排、哪个先闭、哪条描述不对、我漏了什么——都写这儿。）');
写();
写();
写();

const 出 = 行.join('\n') + '\n';
fs.writeFileSync(path.join(根, 'docs', '功能清单-评审稿.md'), 出, 'utf8');
const 问 = 系统.reduce((n, s) => n + (s.待明确 || []).length, 0) + 外.length;
console.log(`已生成 docs/功能清单-评审稿.md（${系统.length} 个系统 · ${问} 处待你明确 · ${出.length} 字符）`);
